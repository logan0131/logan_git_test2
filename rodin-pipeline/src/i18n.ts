export const dictionaries: Record<Lang, Record<Key, string>> = { ko, en };

export type Params = Record<string, string | number>;

export function format(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_m, name: string) => {
    const value = params[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}

export function translate(lang: Lang, key: Key, params?: Params): string {
  return format(dictionaries[lang][key] ?? dictionaries.ko[key] ?? key, params);
}

export type Translate = (key: Key, params?: Params) => string;

export const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void; t: Translate }>({
  lang: "ko",
  setLang: () => undefined,
  t: (key, params) => translate("ko", key, params),
});

export function useT(): Translate {
  return useContext(LangContext).t;
}

const LANG_STORAGE_KEY = "rodin-pipeline-lang";

export function loadStoredLang(): Lang {
  try {
    const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (stored === "ko" || stored === "en") return stored;
  } catch {
    // ignore
  }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("ko") ? "ko" : "en";
}

export function storeLang(lang: Lang): void {
  try {
    window.localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // ignore
  }
}
